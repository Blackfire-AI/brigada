// Command licenses regenerates THIRD_PARTY_NOTICES.md from the real
// dependency tree of ./cmd/brigada, as reported by go-licenses. It
// writes the module name, version, licence name and full licence text
// for every third-party library the binary embeds, and it fails if any
// of those licences is not compatible with brigada's Apache-2.0
// licence.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/google/go-licenses/licenses"
)

const confidenceThreshold = 0.9

const ownModule = "github.com/Blackfire-AI/brigada"

// compatible holds the licence name fragments go-licenses may report
// for licences brigada can embed under Apache-2.0. Anything else, an
// unknown licence included, is refused.
var compatible = []string{"Apache-", "MIT", "BSD-", "ISC", "Zlib", "Unlicense", "CC-BY"}

const noticeTemplate = `<!-- Generated by internal/tools/licenses from go-licenses v1.6.0.
     Do not edit by hand. Regenerate from the repository root with:

         sh internal/tools/licenses/regenerate.sh
-->

# Third-party notices

brigada embeds the third-party Go modules listed below, as reported by
go-licenses for ` + "`./cmd/brigada`" + `. Each entry names the module, its
version, its licence, and the full licence text. The generator refuses
to write this file if any licence is not compatible with brigada's
Apache-2.0 licence ([LICENSE](LICENSE)).
{{range .}}
## {{.Name}} {{.Version}}

Licence: {{.LicenseName}}

` + "```text" + `
{{.LicenseText}}` + "```" + `
{{end}}`

type libraryData struct {
	Name        string
	Version     string
	LicenseName string
	LicenseText string
}

func main() {
	if err := run(os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(1)
	}
}

func run(w io.Writer) error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	if err := os.Chdir(root); err != nil {
		return err
	}
	classifier, err := licenses.NewClassifier(confidenceThreshold)
	if err != nil {
		return err
	}
	libs, err := licenses.Libraries(context.Background(), classifier, false, nil, "./cmd/brigada")
	if err != nil {
		return err
	}
	var data []libraryData
	for _, lib := range libs {
		// The main module has no version and its licence is brigada's
		// own; everything worth reporting is third-party.
		if lib.Version() == "" || strings.HasPrefix(lib.Name(), ownModule) {
			continue
		}
		licensePath := lib.LicensePath
		if licensePath == "" {
			// go-licenses finds a licence only if its classifier can
			// name the file, so a standard licence it fails to name
			// (modernc.org/mathutil's BSD-3-Clause, for one) leaves
			// the library without one. Locate the file in the module
			// cache and classify it ourselves instead of dropping the
			// library from the notices.
			var err error
			if licensePath, err = rescueLicense(lib.Name()); err != nil {
				return fmt.Errorf("%s: no licence found: %w", lib.Name(), err)
			}
		}
		text, err := os.ReadFile(licensePath)
		if err != nil {
			return fmt.Errorf("%s: reading licence: %w", lib.Name(), err)
		}
		licenseText := strings.TrimRight(string(text), "\n") + "\n"
		name, _, err := classifier.Identify(licensePath)
		if err != nil {
			// Fall back to matching the licence text itself, and
			// refuse anything that still has no name.
			fallback, ok := classifyFallback(licenseText)
			if !ok {
				return fmt.Errorf("%s: identifying licence: %w", lib.Name(), err)
			}
			name = fallback
		} else if strings.Contains(licenseText, "Third-Party Software Notices") {
			// Some modules (modernc.org/libc) ship a licence file that
			// aggregates the notices of everything they embed, so a
			// single name from the classifier would understate it.
			name = "Mixed (bundled third-party notices)"
		}
		data = append(data, libraryData{
			Name:        lib.Name(),
			Version:     lib.Version(),
			LicenseName: name,
			LicenseText: licenseText,
		})
	}
	var incompatible []string
	for _, d := range data {
		if !isCompatible(d.LicenseName, d.LicenseText) {
			incompatible = append(incompatible, fmt.Sprintf("%s (%s)", d.Name, d.LicenseName))
		}
	}
	if len(incompatible) > 0 {
		return fmt.Errorf("licences incompatible with Apache-2.0: %s", strings.Join(incompatible, ", "))
	}
	tmpl, err := template.New("notices").Parse(noticeTemplate)
	if err != nil {
		return err
	}
	return tmpl.Execute(w, data)
}

// forbiddenMarkers are the licence texts brigada cannot embed under
// Apache-2.0; a mixed licence file is scanned for them.
var forbiddenMarkers = []string{
	"GNU GENERAL PUBLIC LICENSE",
	"GNU AFFERO GENERAL PUBLIC LICENSE",
	"COMMONS CLAUSE",
	"SERVER SIDE PUBLIC LICENSE",
}

func isCompatible(name, text string) bool {
	if strings.HasPrefix(name, "Mixed") {
		// A bundled notices file carries several licences at once;
		// judge it by what its own text contains.
		upper := strings.ToUpper(text)
		for _, m := range forbiddenMarkers {
			if strings.Contains(upper, m) {
				return false
			}
		}
		return true
	}
	for _, c := range compatible {
		if strings.Contains(name, c) {
			return true
		}
	}
	return false
}

// classifyFallback recognises the standard permissive licence texts by
// their own words, for the files go-licenses' classifier cannot name.
// Anything it does not recognise is reported as unknown.
func classifyFallback(text string) (string, bool) {
	switch {
	case strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0, January 2004"):
		return "Apache-2.0", true
	case strings.Contains(text, "Permission is hereby granted, free of charge"):
		return "MIT", true
	case strings.Contains(text, "Permission to use, copy, modify, and/or distribute this software"):
		return "ISC", true
	case strings.Contains(text, "Redistribution and use in source and binary forms, with or without"):
		if strings.Contains(text, " Neither the name") || strings.Contains(text, " neither the name") {
			return "BSD-3-Clause", true
		}
		return "BSD-2-Clause", true
	default:
		return "", false
	}
}

// repoRoot walks up from the working directory until it finds the
// brigada repository root, recognised by its cmd/brigada package.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "cmd", "brigada")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("repository root (cmd/brigada) not found above %s", dir)
		}
		dir = parent
	}
}

// rescueLicense finds a licence file for a library whose module
// go-licenses could not classify, by looking in the module's directory
// as `go list -m` reports it.
func rescueLicense(name string) (string, error) {
	mods, err := moduleDirs()
	if err != nil {
		return "", err
	}
	segments := strings.Split(name, "/")
	for i := len(segments); i > 0; i-- {
		if dir, ok := mods[strings.Join(segments[:i], "/")]; ok && dir != "" {
			return findLicenseFile(dir)
		}
	}
	return "", fmt.Errorf("module directory for %s not in go list -m all", name)
}

// moduleDirs maps every module of the build list to its directory.
func moduleDirs() (map[string]string, error) {
	out, err := exec.Command("go", "list", "-m", "-json", "all").Output()
	if err != nil {
		return nil, fmt.Errorf("go list -m -json all: %w", err)
	}
	mods := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for dec.More() {
		var m struct {
			Path string
			Dir  string
		}
		if err := dec.Decode(&m); err != nil {
			return nil, err
		}
		mods[m.Path] = m.Dir
	}
	return mods, nil
}

// findLicenseFile picks the licence file of a module directory,
// preferring a plain LICENSE over suffixed or differently named ones.
func findLicenseFile(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	best := ""
	bestScore := -1
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		score := licenseNameScore(e.Name())
		if score > bestScore {
			best, bestScore = filepath.Join(dir, e.Name()), score
		}
	}
	if bestScore < 1 {
		return "", fmt.Errorf("no licence file in %s", dir)
	}
	return best, nil
}

func licenseNameScore(name string) int {
	base := strings.ToLower(name)
	for i, stem := range stems {
		if base == stem || strings.HasPrefix(base, stem+".") {
			// Earlier stems score higher; a plain name scores
			// higher than a suffixed one.
			return (len(stems) - i) * 2
		}
	}
	return 0
}

var stems = []string{"license", "licence", "copying", "notice"}
