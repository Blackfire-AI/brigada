// Command licenses regenerates THIRD_PARTY_NOTICES.md from the real
// dependency tree of ./cmd/brigada, as reported by go-licenses. It
// queries go-licenses once per platform the release workflow builds
// and unions the results, so the file a host generates does not depend
// on the host. It writes the module name, version, licence name and
// full licence text for every third-party library those binaries
// embed, and it fails if any of those licences is not compatible with
// brigada's Apache-2.0 licence.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"

	"github.com/google/go-licenses/licenses"
)

const confidenceThreshold = 0.9

const ownModule = "github.com/Blackfire-AI/brigada"

// compatible holds the licence name fragments go-licenses may report
// for licences brigada can embed under Apache-2.0. Anything else, an
// unknown licence included, is refused.
var compatible = []string{"Apache-", "MIT", "BSD-", "ISC", "Zlib", "Unlicense", "CC-BY"}

// licenceFiles names, relative to the module directory, every licence
// file of a module whose licences go-licenses cannot report as a set.
// modernc.org/libc ships its own BSD-3-Clause LICENSE beside a file that
// gathers the notices of everything it embeds; both are embedded.
var licenceFiles = map[string][]string{
	"modernc.org/libc": {"LICENSE", "LICENSE-3RD-PARTY.md"},
}

const noticeTemplate = `<!-- Generated by internal/tools/licenses from go-licenses v1.6.0.
     Do not edit by hand. Regenerate from the repository root with:

         sh internal/tools/licenses/regenerate.sh
-->

# Third-party notices

brigada embeds the third-party Go modules listed below: the union of
the dependency trees go-licenses reports for ` + "`./cmd/brigada`" + ` on
every platform the release workflow builds. Each entry names the
module, its version, its licence, and the full licence text. The
generator refuses to write this file if any licence is not compatible
with brigada's Apache-2.0 licence ([LICENSE](LICENSE)).
{{range .}}
## {{.Name}} {{.Version}}
{{range .Licences}}
{{if .File}}### {{.File}}

{{end}}Licence: {{.LicenseName}}

` + "```text" + `
{{.LicenseText}}` + "```" + `
{{end}}{{end}}`

type licenceBlock struct {
	File        string
	LicenseName string
	LicenseText string
}

type libraryData struct {
	Name     string
	Version  string
	Licences []licenceBlock
}

func main() {
	if err := run(os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(1)
	}
}

func run(w io.Writer) error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	if err := os.Chdir(root); err != nil {
		return err
	}
	platforms, err := releasePlatforms(filepath.Join(".github", "workflows", "release.yml"))
	if err != nil {
		return err
	}
	classifier, err := licenses.NewClassifier(confidenceThreshold)
	if err != nil {
		return err
	}
	// Build constraints give every release platform its own dependency
	// tree: a file built only on darwin can pull in modules no Linux
	// build ever imports. Union the per-platform sets, so the notices
	// cover what any shipped binary embeds and no host generates a
	// different file.
	byName := map[string]libraryData{}
	for _, platform := range platforms {
		restore := usePlatform(platform[0], platform[1])
		libs, err := licenses.Libraries(context.Background(), classifier, false, nil, "./cmd/brigada")
		restore()
		if err != nil {
			return fmt.Errorf("%s/%s: %w", platform[0], platform[1], err)
		}
		for _, lib := range libs {
			// The main module has no version and its licence is
			// brigada's own; everything worth reporting is third-party.
			if lib.Version() == "" || strings.HasPrefix(lib.Name(), ownModule) {
				continue
			}
			// One go.mod serves every platform, so a module seen on
			// two of them carries the same version and licence both
			// times; the first report wins.
			if _, ok := byName[lib.Name()]; ok {
				continue
			}
			entry, err := libraryEntry(classifier, lib)
			if err != nil {
				return err
			}
			byName[entry.Name] = entry
		}
	}
	data := make([]libraryData, 0, len(byName))
	for _, d := range byName {
		data = append(data, d)
	}
	sort.Slice(data, func(i, j int) bool { return data[i].Name < data[j].Name })
	var incompatible []string
	for _, d := range data {
		for _, b := range d.Licences {
			if !isCompatible(b.LicenseName, b.LicenseText) {
				incompatible = append(incompatible, fmt.Sprintf("%s (%s)", d.Name, b.LicenseName))
			}
		}
	}
	if len(incompatible) > 0 {
		return fmt.Errorf("licences incompatible with Apache-2.0: %s", strings.Join(incompatible, ", "))
	}
	tmpl, err := template.New("notices").Parse(noticeTemplate)
	if err != nil {
		return err
	}
	return tmpl.Execute(w, data)
}

// libraryEntry turns one reported library into a template entry,
// naming its licence file or files and reading their text.
func libraryEntry(classifier licenses.Classifier, lib *licenses.Library) (libraryData, error) {
	var paths []string
	if names, ok := licenceFiles[lib.Name()]; ok {
		dir, err := moduleDir(lib.Name())
		if err != nil {
			return libraryData{}, fmt.Errorf("%s: %w", lib.Name(), err)
		}
		for _, name := range names {
			paths = append(paths, filepath.Join(dir, name))
		}
	} else {
		licensePath := lib.LicensePath
		if licensePath == "" {
			// go-licenses finds a licence only if its classifier can
			// name the file, so a standard licence it fails to name
			// (modernc.org/mathutil's BSD-3-Clause, for one) leaves
			// the library without one. Locate the file in the module
			// cache and classify it ourselves instead of dropping the
			// library from the notices.
			var err error
			if licensePath, err = rescueLicense(lib.Name()); err != nil {
				return libraryData{}, fmt.Errorf("%s: no licence found: %w", lib.Name(), err)
			}
		}
		paths = []string{licensePath}
	}
	var blocks []licenceBlock
	for _, path := range paths {
		block, err := identifyLicence(classifier, path)
		if err != nil {
			return libraryData{}, fmt.Errorf("%s: %w", lib.Name(), err)
		}
		if len(paths) > 1 {
			block.File = filepath.Base(path)
		}
		blocks = append(blocks, block)
	}
	return libraryData{Name: lib.Name(), Version: lib.Version(), Licences: blocks}, nil
}

// workflowLoop matches the build loop of .github/workflows/release.yml,
// whose targets are the platforms brigada ships.
var workflowLoop = regexp.MustCompile(`for target in ([^\n;]+); do`)

// releasePlatforms reads the GOOS/GOARCH targets the release workflow
// cross-compiles from its build loop, so the notices always cover
// exactly the platforms brigada ships.
func releasePlatforms(path string) ([][2]string, error) {
	text, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading the release workflow's build matrix: %w", err)
	}
	m := workflowLoop.FindStringSubmatch(string(text))
	if m == nil {
		return nil, fmt.Errorf("no build loop found in %s", path)
	}
	var platforms [][2]string
	for _, target := range strings.Fields(m[1]) {
		goos, goarch, found := strings.Cut(target, "/")
		if !found {
			return nil, fmt.Errorf("%s: build target %q is not GOOS/GOARCH", path, target)
		}
		platforms = append(platforms, [2]string{goos, goarch})
	}
	return platforms, nil
}

// usePlatform points the go tool that go-licenses and `go list` spawn
// at one release platform, and returns a function restoring the
// previous environment.
func usePlatform(goos, goarch string) func() {
	prevGoos, hadGoos := os.LookupEnv("GOOS")
	prevGoarch, hadGoarch := os.LookupEnv("GOARCH")
	os.Setenv("GOOS", goos)
	os.Setenv("GOARCH", goarch)
	return func() {
		if hadGoos {
			os.Setenv("GOOS", prevGoos)
		} else {
			os.Unsetenv("GOOS")
		}
		if hadGoarch {
			os.Setenv("GOARCH", prevGoarch)
		} else {
			os.Unsetenv("GOARCH")
		}
	}
}

// identifyLicence reads one licence file and names it. Where the
// classifier cannot name it, the text itself is matched.
func identifyLicence(classifier licenses.Classifier, path string) (licenceBlock, error) {
	text, err := os.ReadFile(path)
	if err != nil {
		return licenceBlock{}, fmt.Errorf("reading licence: %w", err)
	}
	licenseText := strings.TrimRight(string(text), "\n") + "\n"
	name, _, err := classifier.Identify(path)
	if err != nil {
		// Fall back to matching the licence text itself, and
		// refuse anything that still has no name.
		fallback, ok := classifyFallback(licenseText)
		if !ok {
			return licenceBlock{}, fmt.Errorf("identifying licence: %w", err)
		}
		name = fallback
	} else if strings.Contains(licenseText, "Third-Party Software Notices") {
		// A file that aggregates the notices of everything a module
		// embeds would be understated by a single name from the
		// classifier.
		name = "Mixed (bundled third-party notices)"
	}
	return licenceBlock{LicenseName: name, LicenseText: licenseText}, nil
}

// forbiddenMarkers are the licence texts brigada cannot embed under
// Apache-2.0; a mixed licence file is scanned for them.
var forbiddenMarkers = []string{
	"GNU GENERAL PUBLIC LICENSE",
	"GNU AFFERO GENERAL PUBLIC LICENSE",
	"COMMONS CLAUSE",
	"SERVER SIDE PUBLIC LICENSE",
}

func isCompatible(name, text string) bool {
	if strings.HasPrefix(name, "Mixed") {
		// A bundled notices file carries several licences at once;
		// judge it by what its own text contains.
		upper := strings.ToUpper(text)
		for _, m := range forbiddenMarkers {
			if strings.Contains(upper, m) {
				return false
			}
		}
		return true
	}
	for _, c := range compatible {
		if strings.Contains(name, c) {
			return true
		}
	}
	return false
}

// classifyFallback recognises the standard permissive licence texts by
// their own words, for the files go-licenses' classifier cannot name.
// Anything it does not recognise is reported as unknown.
func classifyFallback(text string) (string, bool) {
	switch {
	case strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0, January 2004"):
		return "Apache-2.0", true
	case strings.Contains(text, "Permission is hereby granted, free of charge"):
		return "MIT", true
	case strings.Contains(text, "Permission to use, copy, modify, and/or distribute this software"):
		return "ISC", true
	case strings.Contains(text, "Redistribution and use in source and binary forms, with or without"):
		if strings.Contains(text, " Neither the name") || strings.Contains(text, " neither the name") {
			return "BSD-3-Clause", true
		}
		return "BSD-2-Clause", true
	default:
		return "", false
	}
}

// repoRoot walks up from the working directory until it finds the
// brigada repository root, recognised by its cmd/brigada package.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "cmd", "brigada")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("repository root (cmd/brigada) not found above %s", dir)
		}
		dir = parent
	}
}

// rescueLicense finds a licence file for a library whose module
// go-licenses could not classify, by looking in the module's directory.
func rescueLicense(name string) (string, error) {
	dir, err := moduleDir(name)
	if err != nil {
		return "", err
	}
	return findLicenseFile(dir)
}

// moduleDir returns the directory of the module that provides name, as
// `go list -m` reports it.
func moduleDir(name string) (string, error) {
	mods, err := moduleDirs()
	if err != nil {
		return "", err
	}
	segments := strings.Split(name, "/")
	for i := len(segments); i > 0; i-- {
		if dir, ok := mods[strings.Join(segments[:i], "/")]; ok && dir != "" {
			return dir, nil
		}
	}
	return "", fmt.Errorf("module directory for %s not in go list -m all", name)
}

// moduleDirs maps every module of the build list to its directory.
func moduleDirs() (map[string]string, error) {
	out, err := exec.Command("go", "list", "-m", "-json", "all").Output()
	if err != nil {
		return nil, fmt.Errorf("go list -m -json all: %w", err)
	}
	mods := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for dec.More() {
		var m struct {
			Path string
			Dir  string
		}
		if err := dec.Decode(&m); err != nil {
			return nil, err
		}
		mods[m.Path] = m.Dir
	}
	return mods, nil
}

// findLicenseFile picks the licence file of a module directory,
// preferring a plain LICENSE over suffixed or differently named ones.
func findLicenseFile(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	best := ""
	bestScore := -1
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		score := licenseNameScore(e.Name())
		if score > bestScore {
			best, bestScore = filepath.Join(dir, e.Name()), score
		}
	}
	if bestScore < 1 {
		return "", fmt.Errorf("no licence file in %s", dir)
	}
	return best, nil
}

func licenseNameScore(name string) int {
	base := strings.ToLower(name)
	for i, stem := range stems {
		if base == stem || strings.HasPrefix(base, stem+".") {
			// Earlier stems score higher; a plain name scores
			// higher than a suffixed one.
			return (len(stems) - i) * 2
		}
	}
	return 0
}

var stems = []string{"license", "licence", "copying", "notice"}
