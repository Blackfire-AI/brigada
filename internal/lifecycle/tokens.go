package lifecycle

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// The token file's shape (§6.4, §12.1) is `name role[:project] secret`,
// one per line; this package owns the local file's birth and the roles
// the one binary's own clients and runner speak with. The file is the
// authority the API loads; nothing here re-parses its stricter rules.

// The names of the tokens EnsureTokenFile writes: one for the local
// client commands, one for the debug submit's admin calls, one for this
// machine's runner.
const (
	TokenNameClient = "cli"
	TokenNameAdmin  = "admin"
	TokenNameRunner = "runner-1"
)

// EnsureTokenFile creates the token file with fresh secrets when it does
// not exist yet (§6.4): a state directory born by its first engine start
// gets working tokens at once, mode 0600, written through a temp file so
// a concurrent starter never reads half of it.
func EnsureTokenFile(path string) error {
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read the token file %s: %w", path, err)
	}
	secret := func() (string, error) {
		var b [18]byte
		if _, err := rand.Read(b[:]); err != nil {
			return "", fmt.Errorf("mint a token secret: %w", err)
		}
		return hex.EncodeToString(b[:]), nil
	}
	cli, err := secret()
	if err != nil {
		return err
	}
	admin, err := secret()
	if err != nil {
		return err
	}
	runner, err := secret()
	if err != nil {
		return err
	}
	body := fmt.Sprintf("# generated by brigada on first start; the secrets stay in this 0600 file\n"+
		"%s client %s\n%s admin %s\n%s runner %s\n",
		TokenNameClient, cli, TokenNameAdmin, admin, TokenNameRunner, runner)
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tokens-")
	if err != nil {
		return fmt.Errorf("create the token file %s: %w", path, err)
	}
	defer os.Remove(tmp.Name()) // a no-op once the rename below succeeds
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return fmt.Errorf("create the token file %s: %w", path, err)
	}
	if _, err := tmp.WriteString(body); err != nil {
		tmp.Close()
		return fmt.Errorf("create the token file %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("create the token file %s: %w", path, err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		// Someone else created it while we wrote ours: theirs wins, ours
		// goes; both are valid files of fresh secrets.
		if errors.Is(err, os.ErrExist) {
			return nil
		}
		return fmt.Errorf("create the token file %s: %w", path, err)
	}
	return nil
}

// TokenForRole reads the first token of role from the token file, by the
// name it authenticates as. A missing file or a file without the role is
// an error naming the file, so the fix — start an engine once, or add
// the token by hand — is on the line.
func TokenForRole(path, role string) (name, secret string, err error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", "", fmt.Errorf("read the token file %s: %w", path, err)
	}
	for n, raw := range strings.Split(string(data), "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 3 {
			return "", "", fmt.Errorf("token file %s: line %d: want `name role[:project] secret`, got %d fields", path, n+1, len(fields))
		}
		if fields[1] == role {
			return fields[0], fields[2], nil
		}
	}
	return "", "", fmt.Errorf("token file %s: no %s token in it", path, role)
}
