const (
	oldVersion   = "0.9.0"
	oldWorker    = "old worker rule one\nshared line\nold worker last\n"
	oldBugfixTop = "---\nname: bugfix\ndescription: Correcting behavior that fails for a particular case.\n---\n"
	oldBugfix    = oldBugfixTop + "\n# bugfix\n\nold bugfix step\n"
)

// withOldVersion ships a fixture version 0.9.0 beside the embedded one.
func withOldVersion(t *testing.T) {
	t.Helper()
	t.Cleanup(defaults.SetArchiveOverlay(fstest.MapFS{
		"versions/" + oldVersion + "/worker.md":              {Data: []byte(oldWorker)},
		"versions/" + oldVersion + "/skills/bugfix/SKILL.md": {Data: []byte(oldBugfix)},
	}))
}

// oldGenerated is a file generated by version 0.9.0 from text.
func oldGenerated(text string, skill bool) string {
	h := "<!-- brigada: version=" + oldVersion + " digest=" + defaults.Digest(text) + " -->\n"
	if !skill {
		return h + text
	}
	end, _ := skillFrontmatterEnd(text)
	return text[:end] + h + text[end:]
}

// instructionsRepo is a repository with the project.yaml init writes and
// the current defaults generated in it.
func instructionsRepo(t *testing.T) string {
	t.Helper()
	write := importRepo(t)
	base, err := engine.ProjectConfigDefaults(nil, "example.invalid/imported", "true", "none")
	if err != nil {
		t.Fatal(err)
	}
	content, err := engine.ProjectConfigGuidance(base)
	if err != nil {
		t.Fatal(err)
	}
	write(string(content))
	cfg, err := engine.ParseProjectConfig(content)
	if err != nil {
		t.Fatal(err)
	}
	root, _ := os.Getwd()
	applyGuidance(t, root, cfg)
	return root
}

func runCLI(args ...string) (int, string, string) {
	var stdout, stderr bytes.Buffer
	code := run(context.Background(), args, &stdout, &stderr)
	return code, stdout.String(), stderr.String()
}

// TestInstructionsDiffAcrossTwoVersions: files generated by the shipped
// older version are compared with it, found by the header's version, and
// with the current default: unedited and edited, role and skill.
func TestInstructionsDiffAcrossTwoVersions(t *testing.T) {
	withOldVersion(t)
	root := instructionsRepo(t)
	liveWorker, _ := defaults.LiveRoleText("worker")
	firstLive := strings.SplitN(liveWorker, "\n", 2)[0]

	// Unedited worker generated by 0.9.0: nothing of yours, all of brigada's.
	writeRel(t, root, workerRel, oldGenerated(oldWorker, false))
	code, out, errs := runCLI("instructions", "diff", "worker")
	if code != 0 || errs != "" {
		t.Fatalf("diff = %d %q", code, errs)
	}
	for _, want := range []string{"generated from version 0.9.0; current default is version " + defaults.Version, "- old worker rule one", "+ " + firstLive} {
		if !strings.Contains(out, want) {
			t.Errorf("unedited diff lacks %q:\n%s", want, out)
		}
	}
	mine, theirs, _ := strings.Cut(out, "+++ new default")
	if !strings.Contains(mine, "(no differences)") {
		t.Errorf("an unedited file shows edits of yours:\n%s", mine)
	}
	if strings.Contains(theirs, "(no differences)") {
		t.Errorf("the new default shows no change:\n%s", theirs)
	}

	// Edited: your change shows against the generated default, and the
	// default's own change shows against it too.
	writeRel(t, root, workerRel, oldGenerated(oldWorker, false)[:0]+"<!-- brigada: version="+oldVersion+" digest="+defaults.Digest(oldWorker)+" -->\nold worker rule one\nshared line\nMY OWN RULE\n")
	code, out, _ = runCLI("instructions", "diff", "worker")
	mine, theirs, _ = strings.Cut(out, "+++ new default")
	if code != 0 || !strings.Contains(mine, "- old worker last") || !strings.Contains(mine, "+ MY OWN RULE") || strings.Contains(mine, "old worker rule one\n+") {
		t.Errorf("edited diff, your side:\n%s", mine)
	}
	if !strings.Contains(theirs, "- old worker rule one") || !strings.Contains(theirs, "+ "+firstLive) {
		t.Errorf("edited diff, brigada's side:\n%s", theirs)
	}

	// A skill, the same way.
	liveBug, _ := defaults.LiveSkillText("bugfix")
	writeRel(t, root, bugfixRel, oldGenerated(oldBugfix, true))
	_, out, _ = runCLI("instructions", "diff", "bugfix")
	if !strings.Contains(out, "generated from version 0.9.0") || !strings.Contains(out, "- old bugfix step") {
		t.Errorf("skill diff:\n%s", out)
	}
	if !strings.Contains(out, "+ "+strings.Split(strings.TrimPrefix(liveBug[len(oldBugfixTop):], "\n"), "\n")[2]) {
		t.Errorf("skill diff lacks the new default's lines:\n%s", out)
	}
	editedBug := oldGenerated(oldBugfix, true) + "my extra step\n"
	writeRel(t, root, bugfixRel, editedBug)
	_, out, _ = runCLI("instructions", "diff", "bugfix")
	mine, _, _ = strings.Cut(out, "+++ new default")
	if !strings.Contains(mine, "+ my extra step") {
		t.Errorf("edited skill diff, your side:\n%s", mine)
	}
}

// TestInstructionsDiffFallsBackToTwoWay: a header version this brigada does
// not ship, a digest that does not match, or no header at all.
func TestInstructionsDiffFallsBackToTwoWay(t *testing.T) {
	root := instructionsRepo(t)
	for name, tc := range map[string]struct{ file, why string }{
		"unknown version": {"<!-- brigada: version=9.9.9 digest=" + defaults.Digest("x\n") + " -->\nx\n", "version 9.9.9, which this brigada does not ship"},
		"bad digest":      {"<!-- brigada: version=" + defaults.Version + " digest=" + defaults.Digest("other") + " -->\nx\n", "does not match version " + defaults.Version},
		"no header":       {"just my file\n", "no brigada header"},
	} {
		writeRel(t, root, workerRel, tc.file)
		code, out, _ := runCLI("instructions", "diff", "worker")
		if code != 0 || !strings.Contains(out, "two-way diff, because") || !strings.Contains(out, tc.why) || !strings.Contains(out, "--- your file\n+++ new default") {
			t.Errorf("%s: %d\n%s", name, code, out)
		}
		if strings.Contains(out, "generated default") {
			t.Errorf("%s: a three-way diff was printed:\n%s", name, out)
		}
	}
}

// TestInitTakeDefault: the file goes back to the new default under a fresh
// header, edited or stale, role or skill; nothing else is touched.
func TestInitTakeDefault(t *testing.T) {
	withOldVersion(t)
	root := instructionsRepo(t)
	liveWorker, _ := defaults.LiveRoleText("worker")
	liveBug, _ := defaults.LiveSkillText("bugfix")
	writeRel(t, root, workerRel, oldGenerated(oldWorker, false)+"my edit\n")
	writeRel(t, root, bugfixRel, oldGenerated(oldBugfix, true))
	other := readRel(t, root, ".brigada/skills/refactor/SKILL.md")

	for _, name := range []string{"worker", "bugfix"} {
		code, out, errs := runCLI("init", "--take-default", name)
		if code != 0 || errs != "" || !strings.Contains(out, "reset to the default of version "+defaults.Version) {
			t.Fatalf("take-default %s = %d %q %q", name, code, out, errs)
		}
	}
	if got := readRel(t, root, workerRel); got != generatedRoleFile(liveWorker) {
		t.Errorf("worker.md = %.100q", got)
	}
	if got := readRel(t, root, bugfixRel); got != generatedSkillFile(liveBug) {
		t.Errorf("bugfix SKILL.md = %.100q", got)
	}
	if readRel(t, root, ".brigada/skills/refactor/SKILL.md") != other {
		t.Errorf("another skill changed")
	}
	if _, out, _ := runCLI("instructions", "diff", "worker"); strings.Count(out, "(no differences)") != 2 {
		t.Errorf("after take-default the diff still differs:\n%s", out)
	}
	if code, out, _ := runCLI("init", "--take-default", "worker"); code != 0 || !strings.Contains(out, "unchanged") {
		t.Errorf("a second take-default = %d %q", code, out)
	}
	// A deleted file comes back.
	if err := os.Remove(".brigada/instructions/reviewer.md"); err != nil {
		t.Fatal(err)
	}
	if code, _, _ := runCLI("init", "--take-default", "reviewer"); code != 0 || !strings.HasPrefix(readRel(t, root, ".brigada/instructions/reviewer.md"), "<!-- brigada: ") {
		t.Errorf("a deleted file was not recreated")
	}
}

// TestTakeDefaultRestoresRoleKey: a role whose key project.yaml's
// instructions map does not carry (§5.9) gets the key back at its
// default path beside the reset file, so the restore reaches the next
// import; the worker on the instructions_file alias keeps the alias, and
// a role already keyed changes no line of the map.
func TestTakeDefaultRestoresRoleKey(t *testing.T) {
	root := instructionsRepo(t)
	config := readRel(t, root, ".brigada/project.yaml")
	withoutReviewer := strings.Replace(config, "  reviewer: "+engine.DefaultRoleFile("reviewer")+"\n", "", 1)
	if withoutReviewer == config {
		t.Fatalf("the generated project.yaml names no reviewer key:\n%s", config)
	}
	if err := os.WriteFile(filepath.Join(root, ".brigada", "project.yaml"), []byte(withoutReviewer), 0o644); err != nil {
		t.Fatal(err)
	}
	code, out, errs := runCLI("init", "--take-default", "reviewer")
	if code != 0 || errs != "" {
		t.Fatalf("take-default reviewer = %d %q %q", code, out, errs)
	}
	if !strings.Contains(out, "instructions.reviewer key added at the default path") {
		t.Errorf("the restored key was not reported:\n%s", out)
	}
	after := readRel(t, root, ".brigada/project.yaml")
	if !strings.Contains(after, "  reviewer: "+engine.DefaultRoleFile("reviewer")+"\n") {
		t.Errorf("the reviewer key was not restored:\n%s", after)
	}
	if other := strings.Replace(after, "  reviewer: "+engine.DefaultRoleFile("reviewer")+"\n", "", 1); other != withoutReviewer {
		t.Errorf("the restore disturbed other lines:\n%s", after)
	}

	// A role already keyed: the file resets, the map keeps its line.
	if code, out, errs = runCLI("init", "--take-default", "worker"); code != 0 || errs != "" || strings.Contains(out, "key added") {
		t.Fatalf("take-default worker = %d %q %q", code, out, errs)
	}
	if readRel(t, root, ".brigada/project.yaml") != after {
		t.Errorf("a keyed role changed the map")
	}

	// The worker on the alias: the alias's own file is reset and no map
	// key appears beside it, for the file refuses naming the text twice.
	base, err := engine.ProjectConfigDefaults(nil, "example.invalid/imported", "true", "none")
	if err != nil {
		t.Fatal(err)
	}
	alias := string(base) + "instructions_file: .brigada/instructions.md\n"
	if err := os.WriteFile(filepath.Join(root, ".brigada", "project.yaml"), []byte(alias), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, out, errs = runCLI("init", "--take-default", "worker"); code != 0 || errs != "" || strings.Contains(out, "key added") {
		t.Fatalf("take-default worker on the alias = %d %q %q", code, out, errs)
	}
	if readRel(t, root, ".brigada/project.yaml") != alias {
		t.Errorf("the worker gained a map key beside its alias")
	}
	if !strings.HasPrefix(readRel(t, root, ".brigada/instructions.md"), "<!-- brigada: ") {
		t.Errorf("the alias's own file was not reset")
	}
}

// TestInstructionsUsage: usage errors exit 2 and name the way forward, and
// the help names the new forms.
func TestInstructionsUsage(t *testing.T) {
	instructionsRepo(t)
	for name, tc := range map[string]struct {
		args []string
		want string
	}{
		"no subcommand":   {[]string{"instructions"}, "usage: brigada instructions diff <role|skill>"},
		"unknown sub":     {[]string{"instructions", "frob"}, "unknown instructions subcommand"},
		"no name":         {[]string{"instructions", "diff"}, "usage: brigada instructions diff <role|skill>"},
		"two names":       {[]string{"instructions", "diff", "worker", "bugfix"}, "usage: brigada instructions diff"},
		"unknown name":    {[]string{"instructions", "diff", "boss"}, `unknown role or skill "boss"`},
		"take unknown":    {[]string{"init", "--take-default", "boss"}, `unknown role or skill "boss"`},
		"take positional": {[]string{"init", "--take-default", "worker", "extra"}, "no positional arguments"},
	} {
		code, _, errs := runCLI(tc.args...)
		if code != 2 || !strings.Contains(errs, tc.want) {
			t.Errorf("%s: code %d, stderr %q; want 2 with %q", name, code, errs, tc.want)
		}
	}
	if code, _, errs := runCLI("instructions", "diff", "boss"); !strings.Contains(errs, "bugfix") || !strings.Contains(errs, "reviewer") || code != 2 {
		t.Errorf("the unknown-name error does not list the names: %q", errs)
	}
	for args, want := range map[string]string{
		"instructions diff --help": "brigada instructions diff <role|skill>",
		"instructions --help":      "diff",
		"init --help":              "-take-default",
	} {
		code, out, errs := runCLI(strings.Fields(args)...)
		if code != 0 || !strings.Contains(out+errs, want) {
			t.Errorf("%s: code %d, output %q", args, code, out+errs)
		}
	}
	if !strings.Contains(usage, "instructions diff <role|skill>") || !strings.Contains(usage, "--take-default") {
		t.Errorf("the top-level usage does not list the new forms")
	}
}
