// operatorFile is the guide init writes for the user's own coding agent, the
// operator. It is not harness wiring, so --no-wiring does not skip it; init
// overwrites it on every run and brigada remove deletes it.
const operatorFile = ".brigada/operator.md"

const operatorHeaderPrefix = "<!-- Generated by brigada init;"

// operatorGuide stays under 72 columns: init --verbose prints it indented.
const operatorGuide = operatorHeaderPrefix + ` init overwrites it, brigada remove
deletes it. Do not edit. -->

# Operating brigada from your coding agent

You are the operator: the user's own coding agent, outside brigada.
Brigada's foreman plans and its workers build; you pass the user's
requests to the foreman and report back through the brigada CLI. You
hold no approval authority.

## Ask

Send the foreman a request with ` + "`brigada ask -`" + `, the message on stdin:

    brigada ask - <<'EOF'
    Fix the login timeout (issue #12). The issue says: <its text>.
    Relevant code: auth/session.go. Closes #12 in the commit.
    EOF

- The foreman has no shell and cannot read an issue tracker. Read the
  issue yourself and put what it says into the ask; keep the number
  only as a reference for ` + "`Closes`" + ` or ` + "`Refs`" + ` trailers.
- Name files and document sections; the foreman reads the repository.
- Say the build order when tasks depend on each other.
- Hint a tier when a task is easy (light) or risky (heavy); the foreman
  decides.
- If an account is cooling (` + "`brigada status`" + ` shows it), say so, or
  clear a fixed one with ` + "`brigada agent reset <harness>/<model>`" + `.

## Watch

- ` + "`brigada status`" + `: the engine, jobs, plans and what needs the user.
  Pipe it through grep for one plan or task; ` + "`brigada status --line`" + `
  is one short line.
- ` + "`brigada history --task N`" + `: one task's timeline.
- ` + "`brigada history --job N`" + `: one job's timeline, its full verdict.
- ` + "`brigada diff --stat N`" + `: what task N changed, as a diffstat.
- ` + "`brigada top`" + ` is the user's live view; do not run it.

## After a landing

- If the project's land_target is a staging branch and after_land opens
  a pull request, merge that pull request with a merge commit once its
  CI is green.
- If land_target is the default branch and after_land is none, the
  landing is already on the default branch: there is no pull request
  to merge.
- If the engine's or the runner's own code landed and nothing pending
  needs the old behaviour, restart them: ` + "`brigada stop --engine`" + `, then
  ` + "`brigada start`" + `.

## Recover

After an outage (engine down, runner dead, a quota wall), run
` + "`brigada start`" + `, then ` + "`brigada ask`" + ` again: an ask re-wakes the foreman.

## The user's alone

Never do these for the user; say what waits and let them decide:

- ` + "`brigada plan approve`" + ` and ` + "`brigada plan reject`" + `
- ` + "`brigada land approve`" + ` and ` + "`brigada land reject`" + `
- ` + "`brigada push approve`" + `
- ` + "`--and-stop-asking`" + ` on any approval
- tags and releases
- changes to the rules: the approval limit, ` + "`brigada project set`" + `,
  ` + "`.brigada/project.yaml`" + `
`

// planOperatorFile plans the operator guide: written whole, whatever is
// there now. It reads the file and writes nothing.
func planOperatorFile(root string) wireFile {
	return planSteps(root, []wireStep{{operatorFile, func(old []byte, exists bool) ([]byte, string, error) {
		want := []byte(operatorGuide)
		switch {
		case !exists:
			return want, "created", nil
		case bytes.Equal(old, want):
			return old, "unchanged", nil
		}
		return want, "replaced", nil
	}}})[0]
}

// removeOperatorFile deletes the operator guide when it carries init's
// header; any other file at the path is the user's.
func removeOperatorFile(d []byte, exists bool) ([]byte, string, error) {
	if !exists {
		return d, "unchanged", nil
	}
	if !bytes.HasPrefix(d, []byte(operatorHeaderPrefix)) {
		return nil, "", errors.New("no brigada header; keeping your file")
	}
	return nil, "removed", nil
}

// printInitOperatorNote points at the guide after the file plan.
func printInitOperatorNote(w io.Writer) {
	printInitWrapped(w, "", "  ", fmt.Sprintf("Operator guide: %s tells your own coding agent how to work with brigada; have it read that file.", operatorFile))
}
