package main

import (
	"bytes"
	"errors"
	"fmt"
	"io"
)

// operatorFile is the guide init writes for the user's own coding agent, the
// operator. It is not harness wiring, so --no-wiring does not skip it; init
// overwrites it on every run and brigada remove deletes it.
const operatorFile = ".brigada/operator.md"

const operatorHeaderPrefix = "<!-- Generated by brigada init;"

// operatorSkillFile is Claude Code's location for the same guide as a skill.
// Init rewrites it on every run, next to operator.md, and brigada remove
// deletes it.
const operatorSkillFile = ".claude/skills/brigada-operator/SKILL.md"

const operatorHeader = operatorHeaderPrefix + ` init overwrites it, brigada remove
deletes it. Do not edit. -->

`

// operatorSkillFrontmatter opens the skill; Claude Code reads the name and
// the description to decide when to load it.
const operatorSkillFrontmatter = `---
name: brigada-operator
description: Ask brigada's foreman to do work, watch it, follow landings
---

`

// operatorGuide and operatorSkill share operatorBody, the one source of the
// text. Both stay under 72 columns: init --verbose prints them indented.
const operatorGuide = operatorHeader + operatorBody

const operatorSkill = operatorSkillFrontmatter + operatorHeader + operatorBody

const operatorBody = `# Operating brigada from your coding agent

You are the operator: the user's own coding agent, outside brigada.
Brigada's foreman plans and its workers build; you pass the user's
requests to the foreman and report back through the brigada CLI. You
hold no approval authority.

## Ask

Send the foreman a request with ` + "`brigada ask -`" + `, the message on stdin:

    brigada ask - <<'EOF'
    Fix the login timeout (issue #12). The issue says: <its text>.
    Relevant code: auth/session.go. Closes #12 in the commit.
    EOF

- The foreman has no shell. It reads the issues and pull requests of
  the project's own repository with the issue tool. For an issue
  anywhere else, put its text into the ask; keep the number only as
  a reference for ` + "`Closes`" + ` or ` + "`Refs`" + ` trailers.
- Name files and document sections; the foreman reads the repository.
- Say the build order when tasks depend on each other.
- Hint a tier when a task is easy (light) or risky (heavy); the foreman
  decides.
- If an account is cooling (` + "`brigada status`" + ` shows it), say so, or
  clear a fixed one with ` + "`brigada agent reset <harness>/<model>`" + `.

## Watch

- ` + "`brigada status`" + `: the engine, jobs, plans and what needs the user.
  Pipe it through grep for one plan or task; ` + "`brigada status --line`" + `
  is one short line.
- ` + "`brigada history --task N`" + `: one task's timeline.
- ` + "`brigada history --job N`" + `: one job's timeline, its full verdict.
- ` + "`brigada diff --stat N`" + `: what task N changed, as a diffstat.
- ` + "`brigada top`" + ` is the user's live view; do not run it.

## Instructions and skills

Brigada puts the project's instructions into every prompt, one text
per role, and task skills into the prompts of the tasks that name
them. They are files in the repository:

- Role files: ` + "`.brigada/instructions/<role>.md`" + ` for foreman,
  plan_review, worker and reviewer.
- Skills: ` + "`.brigada/skills/<name>/SKILL.md`" + `, in the directory
  project.yaml names as ` + "`skills_dir`" + `.

Edit them like any file, then run ` + "`brigada project import`" + ` to
apply the change; ` + "`brigada status`" + ` flags a file that changed
since the last import. ` + "`brigada instructions diff <role|skill>`" + `
compares a file with the default it came from, and
` + "`brigada init --take-default <role|skill>`" + ` resets it.

To ask for a skill on a task, say so in the ask, naming the task:

    use skill bugfix on task 3
    no skills on task 4

Name only skills that exist under skills_dir. Say "no skills" when a
task should run on the instructions alone.

## After a landing

- If the project's land_target is a staging branch and after_land opens
  a pull request, merge that pull request with a merge commit once its
  CI is green.
- If land_target is the default branch and after_land is none, the
  landing went straight to the default branch: there is no pull
  request to merge.
- If the engine's or the runner's own code landed and nothing pending
  needs the old behaviour, restart them: ` + "`brigada stop --engine`" + `, then
  ` + "`brigada start`" + `.

## Recover

After an outage (engine down, runner dead, a quota wall), run
` + "`brigada start`" + `, then ` + "`brigada ask`" + ` again: an ask re-wakes the foreman.

## The user's alone

Never do these for the user; say what waits and let them decide:

- ` + "`brigada plan approve`" + ` and ` + "`brigada plan reject`" + `
- ` + "`brigada land approve`" + ` and ` + "`brigada land reject`" + `
- ` + "`brigada push approve`" + `
- ` + "`--and-stop-asking`" + ` on any approval
- tags and releases
- changes to the rules: the approval limit, ` + "`brigada project set`" + `,
  ` + "`.brigada/project.yaml`" + `
`

// planOperatorFile plans the operator guide: written whole, whatever is
// there now. It reads the file and writes nothing.
func planOperatorFile(root string) wireFile {
	return planOperatorText(root, operatorFile, operatorGuide)
}

// planOperatorSkill plans the operator skill, written whole like the guide.
func planOperatorSkill(root string) wireFile {
	return planOperatorText(root, operatorSkillFile, operatorSkill)
}

// planOperatorFiles plans every file that carries the operator text.
func planOperatorFiles(root string) []wireFile {
	return []wireFile{planOperatorFile(root), planOperatorSkill(root)}
}

func planOperatorText(root, rel, text string) wireFile {
	return planSteps(root, []wireStep{{rel, func(old []byte, exists bool) ([]byte, string, error) {
		want := []byte(text)
		switch {
		case !exists:
			return want, "created", nil
		case bytes.Equal(old, want):
			return old, "unchanged", nil
		}
		return want, "replaced", nil
	}}})[0]
}

// countChanged counts the files a plan would write or delete.
func countChanged(files []wireFile) int {
	n := 0
	for _, f := range files {
		if f.changed() {
			n++
		}
	}
	return n
}

// removeOperatorFile deletes the operator guide when it carries init's
// header; any other file at the path is the user's.
func removeOperatorFile(d []byte, exists bool) ([]byte, string, error) {
	if !exists {
		return d, "unchanged", nil
	}
	if !bytes.HasPrefix(d, []byte(operatorHeaderPrefix)) {
		return nil, "", errors.New("no brigada header; keeping your file")
	}
	return nil, "removed", nil
}

// removeOperatorSkill deletes the operator skill when it carries init's
// header after its frontmatter; any other file at the path is the user's.
func removeOperatorSkill(d []byte, exists bool) ([]byte, string, error) {
	if !exists {
		return d, "unchanged", nil
	}
	if !bytes.Contains(d, []byte(operatorHeaderPrefix)) {
		return nil, "", errors.New("no brigada header; keeping your file")
	}
	return nil, "removed", nil
}

// printInitOperatorNote points at the guide after the file plan.
func printInitOperatorNote(w io.Writer) {
	printInitWrapped(w, "", "  ", fmt.Sprintf("Operator guide: %s tells your own coding agent how to work with brigada; have it read that file.", operatorFile))
}
