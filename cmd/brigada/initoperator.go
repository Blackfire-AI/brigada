package main

import (
	"bytes"
	"errors"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// operatorFile is the guide an older init wrote for the user's own coding
// agent, the operator. Init writes it no more (§4, §13.1): the operator
// procedure is the canonical skills/brigada-operator/SKILL.md, which the
// user installs with the skills CLI. A rerun of init and brigada remove
// delete a copy that carries init's generated header.
const operatorFile = ".brigada/operator.md"

// operatorHeaderPrefix opens every operator file init generated. A file at
// either legacy path without it is the user's and stays.
const operatorHeaderPrefix = "<!-- Generated by brigada init;"

// operatorSkillFile is where an older init wrote the same guide as a skill
// for Claude Code. The skills CLI installs the canonical skill there too,
// behind a symlink: that one is not brigada's and never goes.
const operatorSkillFile = ".claude/skills/brigada-operator/SKILL.md"

// operatorSkillInstall is how the user installs the operator skill into a
// coding agent's harness. Init prints it and never runs it, so brigada
// takes no Node.js dependency and writes no harness configuration.
const operatorSkillInstall = "npx skills add Blackfire-AI/brigada --skill brigada-operator"

// installedSkillPurpose describes the plan's one row for a skill the skills
// CLI installed behind a symlink at the legacy path: brigada reads nothing
// there and changes nothing.
const installedSkillPurpose = "an installed skill brigada does not manage"

// planLegacyOperator plans what a rerun of init and brigada remove do with
// the operator artifacts an older init generated. Each goes when it carries
// init's header; any other file at the path is the user's, stays, and the
// plan says so. It reads files and writes nothing.
func planLegacyOperator(root string) []wireFile {
	guide := wireStep{operatorFile, removeOperatorFile}
	skill := wireStep{operatorSkillFile, removeOperatorSkill}
	// The skills CLI installs the canonical skill behind a symlink at the
	// legacy path's directory, which planSteps refuses like every symlink.
	// That skill is not brigada's: it stays, as one quiet row.
	if skillInstalled(root) {
		return append(planSteps(root, []wireStep{guide}), installedSkill(root))
	}
	return planSteps(root, []wireStep{guide, skill})
}

// skillInstalled reports whether a skill is installed at the legacy path
// behind a symlink, as the skills CLI installs it: the path is refused,
// yet a file is there. Brigada never follows a link, so it resolves the
// path and reads nothing.
func skillInstalled(root string) bool {
	if wiringSafePath(root, operatorSkillFile) == nil {
		return false
	}
	_, err := os.Stat(filepath.Join(root, filepath.FromSlash(operatorSkillFile)))
	return err == nil
}

// installedSkill is the plan's quiet row for the skill installed at the
// legacy path: it is there, brigada does not manage it, nothing changes.
func installedSkill(root string) wireFile {
	return wireFile{root: root, rel: operatorSkillFile, path: filepath.Join(root, filepath.FromSlash(operatorSkillFile)),
		exists: true, state: "unchanged", purpose: installedSkillPurpose}
}

// countChanged counts the files a plan would write or delete.
func countChanged(files []wireFile) int {
	n := 0
	for _, f := range files {
		if f.changed() {
			n++
		}
	}
	return n
}

// removeOperatorFile deletes the operator guide when it opens with init's
// header; any other file at the path is the user's.
func removeOperatorFile(d []byte, exists bool) ([]byte, string, error) {
	if !exists {
		return d, "unchanged", nil
	}
	if !bytes.HasPrefix(d, []byte(operatorHeaderPrefix)) {
		return nil, "", errors.New("no brigada header; keeping your file")
	}
	return nil, "removed", nil
}

// removeOperatorSkill deletes the operator skill when it carries init's
// header after its frontmatter; any other file at the path is the user's, a
// copy of the canonical skill included.
func removeOperatorSkill(d []byte, exists bool) ([]byte, string, error) {
	if !exists {
		return d, "unchanged", nil
	}
	if !bytes.Contains(d, []byte(operatorHeaderPrefix)) {
		return nil, "", errors.New("no brigada header; keeping your file")
	}
	return nil, "removed", nil
}

// printInitOperatorSkill closes the plan with the operator skill's
// installation command. Init prints it and never runs it.
func printInitOperatorSkill(w io.Writer) {
	printInitWords(w, "  "+initPresentation(w).style.Bold("Operator skill:")+" ", "    ", operatorSkillWords(w,
		"your own coding agent works with brigada through the brigada-operator skill, which init does not install. Add -g to install it globally; npx skills update advances it. Install it with:"))
}

// operatorSkillWords wraps prose at its spaces and keeps the installation
// command whole, so no line breaks inside it.
func operatorSkillWords(w io.Writer, prose string) []initWord {
	var words []initWord
	for _, word := range strings.Fields(prose) {
		words = append(words, initWord{" ", word})
	}
	return append(words, initWord{" ", initPresentation(w).style.Accent(operatorSkillInstall)})
}
